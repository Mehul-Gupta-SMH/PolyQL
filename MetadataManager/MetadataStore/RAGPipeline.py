class ManageInformation:
    """
    A class for managing information in a database.

    attr:
        - dbName (str): Name of the database being managed.
        - client: Client object for interacting with the database.
        - embedding_model: Sentence embedding model for generating embeddings.
    """

    def __init__(self):
        """
        Initialize the ManageInformation instance.
        """
        self.vectordb_configs = get_config_val("retrieval_config", ["vectordb"], True)

        self.dbName = self.vectordb_configs["name"]
        self.vdb = None
        self.embedding_model = get_embedding_model()
        self.FilterScoreObj = FilterContext()

    def initialize_client(self):
        """
        Initialize the vector store connection.

        Notes:
            - Currently supports 'chroma'. Swap ChromaVectorStore for any
              other BaseVectorStore implementation to change backends.
        """
        if self.dbName == 'chroma':
            self.vdb = ChromaVectorStore()
            self.vdb.client = get_chroma_client(self.vectordb_configs["path"])

    def add_new_data(self, data, data_metadata, vdb_metadata):
        """
        Add new data to the vector store.

        Args:
            data: Data to be added.
            data_metadata: Metadata for the data.
            vdb_metadata: Metadata specific to the virtual database (vdb).

        Returns:
            - str: Message indicating the success of the operation.
        """
        embedding_data = [
            {
                'documents': str(data),
                'embedding': self.embedding_model.encode(str(data)).tolist(),
                'metadata': data_metadata,
                'id': str(uuid.uuid3(uuid.NAMESPACE_DNS, str(data)))
            }
        ]

        self.vdb.add_data(embedding_data, vdb_metadata)

        return "Success"

    def get_data(self, query, vdb_metadata, instance_name: str = None):
        """
        Retrieve data from the vector store and score each result.

        Args:
            query: Query to retrieve data.
            vdb_metadata: Metadata specific to the virtual database.
            instance_name (str): Optional instance filter. When provided and not "default",
                passes DB=instance_name as a ChromaDB where-filter so only documents
                belonging to that instance are returned.

        Returns:
            dict: Scored results containing retrieved data, distance, and scores.
        """
        query_embed = self.embedding_model.encode(query).tolist()

        # Apply instance filter only when a non-default instance is requested.
        # Existing documents may not have DB="default" set, so we avoid filtering
        # the default instance to maintain backward compatibility.
        extra_filters = {}
        if instance_name and instance_name != "default":
            extra_filters["DB"] = instance_name

        retrieved_info = self.vdb.get_data(query_embed, vdb_metadata, **extra_filters)

        results_scored = {}
        for ind in range(len(retrieved_info['ids'][0])):
            results_scored[retrieved_info['ids'][0][ind]] = {
                'data':     retrieved_info['documents'][0][ind],
                'metadata': retrieved_info['metadatas'][0][ind],
                'distance': retrieved_info['distances'][0][ind],
                'scores':   self.FilterScoreObj.ScoreResults(
                                query, retrieved_info['documents'][0][ind]
                            )
            }

        return results_scored

